open Domain
open Lang
open Util.Source

(* Extract (type_id_string * mixop * alter) from TypD VariantT print hints *)

let extract_hints (spec : Sl.spec) : (string * Mixop.t * Hints.Alter.t) list =
  List.concat_map
    (fun def ->
      match def.it with
      | Sl.TypD (id, _, deftyp, _) -> (
          match deftyp.it with
          | Il.VariantT typcases ->
              List.filter_map
                (fun (nottyp, _, hints) ->
                  let hint_exp_opt =
                    List.find_opt (fun h -> El.(h.hintid.it = "print")) hints
                    |> Option.map (fun h -> El.(h.hintexp))
                  in
                  let hint_alter_opt =
                    Option.bind hint_exp_opt Hints.Alter.init
                  in
                  match hint_alter_opt with
                  | None -> None
                  | Some alter ->
                      let mixop, _ = Mixfix.split nottyp.it in
                      Some (id.it, mixop, alter))
                typcases
          | _ -> [])
      | _ -> [])
    spec

(* Serialize Hints.Alter.t to an OCaml source expression string *)

let rec serialize_alter (alter : Hints.Alter.t) : string =
  match alter with
  | Hints.Alter.TextH s ->
      Printf.sprintf "Hints.Alter.TextH \"%s\"" (String.escaped s)
  | Hints.Alter.AtomH atom ->
      Printf.sprintf "Hints.Alter.AtomH (%s)"
        (Interface.Dynamic_gen.make_atom_phrase_string atom)
  | Hints.Alter.SeqH hints ->
      Printf.sprintf "Hints.Alter.SeqH [%s]"
        (String.concat "; " (List.map serialize_alter hints))
  | Hints.Alter.BrackH (l, h, r) ->
      Printf.sprintf "Hints.Alter.BrackH (%s, %s, %s)"
        (Interface.Dynamic_gen.make_atom_phrase_string l)
        (serialize_alter h)
        (Interface.Dynamic_gen.make_atom_phrase_string r)
  | Hints.Alter.HoleH `Next -> "Hints.Alter.HoleH `Next"
  | Hints.Alter.HoleH (`Num i) ->
      Printf.sprintf "(Hints.Alter.HoleH (`Num %d))" i
  | Hints.Alter.FuseH (h1, h2) ->
      Printf.sprintf "Hints.Alter.FuseH (%s, %s)" (serialize_alter h1)
        (serialize_alter h2)
  | Hints.Alter.OtherH _ ->
      Printf.eprintf
        "Warning: OtherH in print hint encountered — emitting assert false\n";
      "(assert false)"

(* Write unparse_compiled.ml *)

let compile_spec (_ctx : Ctx.t) (spec : Sl.spec) ~(path_out : string) : unit =
  let entries = extract_hints spec in
  let buf = Buffer.create 4096 in
  let pr fmt = Printf.bprintf buf fmt in
  pr "(* Generated by make gen-ocaml — do not edit *)\n";
  pr "open Domain\n";
  pr "open Lang\n";
  pr "module Value = Runtime.Value\n";
  pr "open Util.Source\n";
  pr "\n";
  pr "let henv : Unparse.HEnv.t =\n";
  pr "  let entries =\n";
  pr "    [\n";
  List.iter
    (fun (tid, mixop, alter) ->
      pr "      (\"%s\",\n" (String.escaped tid);
      pr "       %s,\n" (Interface.Dynamic_gen.make_mixop_string mixop);
      pr "       %s);\n" (serialize_alter alter))
    entries;
  pr "    ]\n";
  pr "  in\n";
  pr "  List.fold_left\n";
  pr "    (fun acc (tid, mixop, hint) ->\n";
  pr "      Unparse.HEnv.add (tid $ no_region, mixop) hint acc)\n";
  pr "    Unparse.HEnv.empty entries\n";
  pr "\n";
  pr "let print (value : Value.t) : string =\n";
  pr "  Format.asprintf \"%%a\" (Unparse.pp_value henv) value\n";
  let oc = open_out path_out in
  output_string oc (Buffer.contents buf);
  close_out oc
